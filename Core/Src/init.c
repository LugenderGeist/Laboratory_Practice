#include "init.h"

void GPIO_Init (void){
RCC_GPIO_EN;
GPIOB_PPUP;

GPIOB_MODER |= GPIO_SET0;
GPIOB_OSPEED |= GPIO_SET0;

GPIOB_MODER |= GPIO_SET1;
GPIOB_OSPEED |= GPIO_SET1;

GPIOB_MODER |= GPIO_SET2;
GPIOB_OSPEED |= GPIO_SET2;

GPIOB_MODER |= GPIO_SET3;
GPIOB_OSPEED |= GPIO_SET3;

GPIOB_MODER |= GPIO_SET4;
GPIOB_OSPEED |= GPIO_SET4;

GPIOB_MODER |= GPIO_SET5;
GPIOB_OSPEED |= GPIO_SET5;

}